students = [
    ("Іванов", "КБ-25", [90, 80, 85]),
    ("Петров", "КБ-25", [70, 75, 80]),
    ("Сидоров", "КБ-26", [95, 90, 99])
]

# Таблиця та розпакування
print("Прізвище | Група | Оцінки")
print("-------------------------")
for st in students:
    name, group, marks = st # Розпакування
    print(name, "  |", group, "|", marks)

# Загальна сума всіх оцінок
total_sum = 0
for st in students:
    total_sum = total_sum + sum(st[2])

print("\nЗагальна сума всіх оцінок:", total_sum, "балів")

